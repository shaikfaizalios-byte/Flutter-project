"""Writes the exam data the app needs before it can reach the server.

    python scripts/export_exam_data.py

Reads services/api/data/exam_templates (the defaults and the featured, verified exams) and
writes apps/mobile/lib/core/exams/exam_data.g.dart. tests/test_exam_profile.py fails when the
file is out of date.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = ROOT / "services" / "api" / "data" / "exam_templates"
TARGET = ROOT / "apps" / "mobile" / "lib" / "core" / "exams" / "exam_data.g.dart"
PROFILE_FIELDS = (
    "kind",
    "options_per_question",
    "repeat_share",
    "min_papers",
    "reliable_papers",
    "counting_unit",
)


def render() -> str:
    defaults = json.loads((TEMPLATES / "defaults.json").read_text(encoding="utf-8"))
    templates = [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(TEMPLATES.glob("*.json"))
        if path.name != "defaults.json"
    ]
    built_in = sorted(
        (t for t in templates if t["status"] == "verified" and t.get("featured")),
        key=lambda t: t["sort_order"],
    )
    data = {
        "defaults": {field: defaults[field] for field in PROFILE_FIELDS},
        "exams": [
            {
                "code": t["code"],
                "name": t["name"],
                "short_name": t["short_name"],
                "category": t["category"],
                "featured": True,
                "profile": {field: t[field] for field in PROFILE_FIELDS},
            }
            for t in built_in
        ],
    }
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by scripts/export_exam_data.py from services/api/data/exam_templates.\n"
        "// Do not edit.\n\n"
        f"const examDataJson = r'''\n{body}\n''';\n"
    )


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET}")
