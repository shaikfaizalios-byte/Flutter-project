"""Storage for original uploaded files.

Keys are generated by the service (``documents/<uuid>.pdf``); user-supplied names never reach
the filesystem. ``LocalDocumentStorage`` additionally refuses any key that would resolve
outside its root, as defence in depth against path traversal.
"""

import shutil
import uuid
from pathlib import Path
from typing import Protocol


class StorageKeyError(ValueError):
    """The key is malformed or points outside the storage root."""


class DocumentStorage(Protocol):
    def new_key(self) -> str: ...

    def save(self, key: str, source: Path) -> None:
        """Move ``source`` into storage under ``key``."""

    def path_for(self, key: str) -> Path:
        """Local filesystem path for reading the stored file."""

    def delete(self, key: str) -> None:
        """Remove the file; a missing file is not an error."""

    def temp_dir(self) -> Path:
        """Directory for in-progress uploads (same filesystem, so ``save`` is a rename)."""


class LocalDocumentStorage:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()
        (self._root / "documents").mkdir(parents=True, exist_ok=True)
        (self._root / "tmp").mkdir(parents=True, exist_ok=True)

    def new_key(self) -> str:
        return f"documents/{uuid.uuid4().hex}.pdf"

    def path_for(self, key: str) -> Path:
        path = (self._root / key).resolve()
        if not path.is_relative_to(self._root / "documents") or path.suffix != ".pdf":
            raise StorageKeyError("Invalid storage key.")
        return path

    def save(self, key: str, source: Path) -> None:
        destination = self.path_for(key)
        shutil.move(source, destination)

    def delete(self, key: str) -> None:
        self.path_for(key).unlink(missing_ok=True)

    def temp_dir(self) -> Path:
        return self._root / "tmp"
